pub fn keycode_for_usage(usage: u16) -> Option<u16> {
    USAGE_KEYCODES
        .iter()
        .find(|(u, _)| *u == usage)
        .map(|(_, code)| *code)
}

pub fn usage_for_keycode(code: u16) -> Option<u16> {
    USAGE_KEYCODES
        .iter()
        .find(|(_, c)| *c == code)
        .map(|(usage, _)| *usage)
}
